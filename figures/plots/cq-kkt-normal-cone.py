"""Prepared Lecture 20 geometry/proof sketch; analytic inputs, no solver results.
One source serves the handout and Constraint-Qualifications website reference.
Direct labels, line styles and hatches preserve meaning in greyscale.

Example min 2x1+x2 s.t. x1>=0, x2>=0 at x*=0.
Left: the feasible set S, the objective gradient and the objective contour
through the origin; grad f^T d >= 0 holds on all of S.
Right: -grad f lies in the cone generated by the active constraint gradients.
Multiplier values are deliberately NOT printed (the handout asks for them).
"""
import numpy as np
import matplotlib.pyplot as plt

BLUE, ORANGE = '#0072B2', '#D55E00'

def _axes(ax):
    ax.axhline(0, color='black', lw=.7)
    ax.axvline(0, color='black', lw=.7)
    ax.set_aspect('equal')
    ax.set(xlim=(-2.9, 2.9), ylim=(-1.9, 1.9), xlabel='$x_1$', ylabel='$x_2$')

def _arrow(ax, v, col, lw=3, ls='-'):
    ax.annotate('', xy=v, xytext=(0, 0),
                arrowprops=dict(arrowstyle='->', color=col, lw=lw, ls=ls))

def make_figure():
    fig, axes = plt.subplots(1, 2, figsize=(7.4, 3.2))
    ax = axes[0]
    _axes(ax)
    ax.fill_between([0, 2.9], 0, 1.9, facecolor='0.9', edgecolor='0.6',
                    hatch='//', alpha=.5)
    ax.plot([-.95, .95], [1.9, -1.9], color='black', ls='--', lw=1.4)
    ax.text(.95, -1.55, r'$f=0$', fontsize=10, ha='left')
    _arrow(ax, (2, 1), 'black')
    ax.text(2.05, 1.02, r'$\nabla f$', fontsize=12)
    ax.text(2.3, .2, r'$S$', fontsize=12)
    ax.set_title(r'$\nabla f^T\mathbf{d}\geq0$ on $S$',
                 fontsize=10)
    ax = axes[1]
    _axes(ax)
    ax.fill_between([-2.9, 0], -1.9, 0, facecolor='0.9', edgecolor='0.6',
                    hatch='\\\\', alpha=.5)
    _arrow(ax, (-1, 0), BLUE)
    _arrow(ax, (0, -1), ORANGE)
    _arrow(ax, (-2, -1), 'black', ls='-')
    ax.text(-1.0, .18, r'$\nabla g_1$', fontsize=12, color=BLUE)
    ax.text(.12, -1.0, r'$\nabla g_2$', fontsize=12, color=ORANGE)
    ax.text(-1.55, -1.3, r'$-\nabla f$', fontsize=12)
    ax.text(-2.85, -1.72, 'cone of active gradients', fontsize=9)
    ax.set_title(r'$-\nabla f$ and the active gradients',
                 fontsize=10)
    fig.tight_layout()
    return fig
