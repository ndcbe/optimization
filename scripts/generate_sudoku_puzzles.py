# ---------------------------------------------------------------------------
# Sudoku-preserving scrambling operations
#
# Throughout, `board` is a list of n lists of n ints, and `l` is sqrt(n): the
# side length of one subgrid, and therefore also the number of subgrid bands.
# Row index `a * l + b` is row b of band a.
# ---------------------------------------------------------------------------


def swap_rows_within_band(board, l, rng):
    """Swap two distinct rows that pass through the same band of subgrids."""
    a = rng.randint(0, l - 1)
    b = rng.randint(0, l - 1)
    c = rng.randint(0, l - 1)
    while c == b:
        c = rng.randint(0, l - 1)
    board[a * l + b], board[a * l + c] = board[a * l + c], board[a * l + b]
    return board


def swap_row_bands(board, l, rng):
    """Swap two whole bands of l rows."""
    a = rng.randint(0, l - 1)
    b = rng.randint(0, l - 1)
    while a == b:
        b = rng.randint(0, l - 1)
    for i in range(l):
        board[a * l + i], board[b * l + i] = board[b * l + i], board[a * l + i]
    return board


def swap_cols_within_band(board, l, rng):
    """Swap two distinct columns that pass through the same band of subgrids."""
    a = rng.randint(0, l - 1)
    b = rng.randint(0, l - 1)
    c = rng.randint(0, l - 1)
    while c == b:
        c = rng.randint(0, l - 1)
    for row in board:
        row[a * l + b], row[a * l + c] = row[a * l + c], row[a * l + b]
    return board


def swap_col_bands(board, l, rng):
    """Swap two whole bands of l columns."""
    a = rng.randint(0, l - 1)
    b = rng.randint(0, l - 1)
    while a == b:
        b = rng.randint(0, l - 1)
    for i in range(l):
        for row in board:
            row[a * l + i], row[b * l + i] = row[b * l + i], row[a * l + i]
    return board


def scramble_board(board, l, rng):
    """Apply ~1000 random sudoku-preserving moves to a solved board."""
    for _ in range(rng.randint(1000, 1100)):
        d = rng.randint(0, 5)
        if d == 0:
            board = swap_col_bands(board, l, rng)
        elif d == 1:
            board = swap_row_bands(board, l, rng)
        elif d <= 3:
            board = swap_rows_within_band(board, l, rng)
        else:
            board = swap_cols_within_band(board, l, rng)
    return board


def blank_cells(board, n, rng):
    """Turn a solved board into a puzzle by setting some cells to 0."""
    if n not in BLANKS:
        raise ValueError(f"No blank count defined for puzzle size {n}")
    blanks = rng.randint(*BLANKS[n])
    for row, col in rng.sample(list(product(range(n), range(n))), blanks):
        board[row][col] = 0
    return board


def generate_puzzles(seed_board, num_puzzles=NUM_PUZZLES, rng=random):
    """Generate `num_puzzles` random unsolved puzzles from one solved board."""
    n = len(seed_board)
    l = int(math.sqrt(n))
    puzzles = []
    for _ in range(num_puzzles):
        board = [row[:] for row in seed_board]  # never mutate the seed
        puzzles.append(blank_cells(scramble_board(board, l, rng), n, rng))
    return puzzles


def puzzles_to_csv_text(puzzles):
    """Serialise puzzles as CSV text: one flattened puzzle per row."""
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\r\n")
    for puzzle in puzzles:
        writer.writerow([cell for row in puzzle for cell in row])
    return buffer.getvalue()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seed", type=int, default=0, help="RNG seed (default 0)")
    parser.add_argument(
        "--num-puzzles", type=int, default=NUM_PUZZLES, help="puzzles per size"
    )
    parser.add_argument(
        "--sizes",
        type=int,
        nargs="+",
        default=[len(b) for b in SEED_BOARDS],
        help="puzzle sizes to generate (default: all five)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed CSVs reproduce; write nothing",
    )
    args = parser.parse_args(argv)

    by_size = {len(b): b for b in SEED_BOARDS}

    # Seed once, then walk the sizes in the canonical order. The RNG stream is
    # shared across sizes, so generating a SUBSET does not reproduce the
    # committed files -- --sizes is for experimenting, not for regenerating.
    random.seed(args.seed)
    subset = sorted(args.sizes) != sorted(by_size)

    failures = 0
    for n, seed_board in sorted(by_size.items()):
        text = puzzles_to_csv_text(
            generate_puzzles(seed_board, args.num_puzzles, random)
        )
        if n not in args.sizes:
            continue  # consume the RNG stream, but do not touch the file
        path = DATA_DIR / f"sudoku_puzzles_{n}.csv"
        if args.check:
            existing = path.read_text(newline="") if path.exists() else None
            match = existing == text
            failures += not match
            print(f"{path.name}: {'reproduces' if match else 'DIFFERS'}")
        else:
            path.write_text(text, newline="")
            print(f"wrote {path} ({args.num_puzzles} puzzles, {n}x{n})")

    if subset:
        print(
            "note: --sizes was given, so the RNG stream still advanced through "
            "every size to keep the output identical to a full run.",
            file=sys.stderr,
        )
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
