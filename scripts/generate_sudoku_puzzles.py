"""Generate the sudoku puzzle datasets consumed by notebooks/1-dev/Sudoku_Solver.ipynb.

The notebook *solves* puzzles; it does not make them. The generation code used to
live in the notebook itself -- three code cells totalling ~46 kB, of which 41 kB
was five hardcoded solved boards that simply duplicated the CSV files they
produced. It was moved here on 2026-08-25 so the notebook only consumes
``notebooks/data/sudoku_puzzles_<n>.csv``.

How a random puzzle is made
---------------------------
1. Start from a known *solved* board of size n (the ``SEED_BOARDS`` below).
2. Scramble it with operations that preserve the sudoku property: swap two rows
   that pass through the same band of subgrids, swap two whole bands of rows,
   and the two column analogues. Any composition of these maps a solved board to
   a different solved board.
3. Blank out a size-dependent number of cells to make the puzzle.

Note this does **not** guarantee a unique solution -- see the notebook's
Conclusion. A puzzle with several completions is still a perfectly good MILP
feasibility instance, which is what the notebook uses it for.

Reproducibility
---------------
The generator is seeded (``--seed``, default 0) and is byte-for-byte
reproducible: running

    python scripts/generate_sudoku_puzzles.py

regenerates the committed CSVs exactly, leaving ``git status`` clean. Verified
2026-08-25 for all five sizes. ``--check`` asserts that rather than writing.

Usage
-----
    python scripts/generate_sudoku_puzzles.py              # rewrite the CSVs
    python scripts/generate_sudoku_puzzles.py --check      # verify, write nothing
    python scripts/generate_sudoku_puzzles.py --sizes 4 9  # a subset
"""

